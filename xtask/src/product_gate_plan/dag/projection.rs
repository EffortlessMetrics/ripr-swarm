const BRANCH_END: &str = r#"
      - name: Record native outcomes against expected rows
        if: always() && steps.verify_plan.outcome == 'success'
        env:
          RIPR_DAG_STEPS: ${{ toJSON(steps) }}
          BRANCH: ${{ inputs.branch }}
          START: ${{ steps.clock.outputs.start }}
        run: '"$RUNNER_TEMP/rust-dag-controller-target/debug/xtask" product-gate-dag record .dag/plan.json "$BRANCH" "result-$BRANCH.json" "$START"'
      - name: Retain branch receipt
        if: always()
        uses: actions/upload-artifact@cf430e030ddbb5b0abf93d22962f4752f3646cd9
        with:
          name: rust-dag-result-${{ inputs.branch }}-${{ github.run_id }}-${{ github.run_attempt }}
          path: result-${{ inputs.branch }}.json
          if-no-files-found: error
          retention-days: 5
"#;

const TRUSTED_CONTROLLER: &str = r#"      - name: Compile trusted base controller in private state
        working-directory: controller
        run: |
          mkdir -p target
          cargo build --locked -p xtask --bin xtask --target-dir "$RUNNER_TEMP/rust-dag-controller-target"
      - name: Verify immutable plan before allocating producer commands
        id: verify_plan
        run: '"$RUNNER_TEMP/rust-dag-controller-target/debug/xtask" product-gate-dag verify .dag/plan.json'
"#;

#[cfg(test)]
mod tests {
    use super::*;
    const SOURCE_BYTES: &str = include_str!("../../../../.github/workflows/rust-gates.yml");
    #[test]
    fn projection_preserves_commands_and_actual_data_edges() -> Result<(), String> {
        let rendered = render(SOURCE_BYTES)?;
        for gate in definitions() {
            assert_eq!(
                rendered
                    .matches(&format!("      - name: {}\n", gate.id.step_name()))
                    .count(),
                1
            );
        }
        assert!(rendered.find("name: PR evidence") < rendered.find("name: Schema producer sweep"));
        assert!(
            rendered.find("name: Golden output contracts")
                < rendered.find("name: Retain wildcard calibration producer outputs")
        );
        let preparation =
            rendered.find("name: Prepare default workspace before native policy inventory");
        assert!(rendered.find("name: Formatting preflight") < preparation);
        assert!(rendered.find("name: Agent skill contracts") < preparation);
        assert!(preparation < rendered.find("name: Repository policy preflight"));
        assert!(
            rendered.find("name: Repository policy preflight")
                < rendered.find("name: Required Rust tests")
        );
        assert!(rendered.contains("id: workspace_preparation"));
        assert!(rendered.contains("inputs.branch == 'tests' && (success())"));
        // The existing shard producer owns this compilation shape. It is not
        // a replacement for the unchanged nextest test execution below.
        assert!(
            include_str!("../../../../.github/workflows/rust-test-shards.yml")
                .contains("cargo test --no-run --locked --workspace\n")
        );
        assert!(rendered.contains("cargo nextest run --workspace --profile ci\n"));
        assert!(rendered.contains("cargo test --workspace --doc\n"));
        assert!(rendered.contains(
            "--artifact schemas/ripr/review-comments.schema.json=target/ripr/review/comments.json"
        ));
        Ok(())
    }
    #[test]
    fn omitted_or_duplicated_required_producer_is_not_projectable() {
        let missing = SOURCE_BYTES.replace(
            "name: Required Rust doctests",
            "name: accidentally omitted doctests",
        );
        assert!(render(&missing).is_err());
        let duplicate = format!(
            "{SOURCE_BYTES}\n      - name: Strict workspace Clippy\n        run: cargo clippy\n"
        );
        assert!(render(&duplicate).is_err());
        let unknown = format!(
            "{SOURCE_BYTES}\n      - name: New required proof\n        run: cargo xtask new-required-proof\n"
        );
        assert!(render(&unknown).is_err());
        let explicit_preparation = SOURCE_BYTES.replace(
            "      - name: Repository policy preflight",
            "      - name: Prepare default workspace before native policy inventory\n        run: cargo test --no-run --locked --workspace\n      - name: Repository policy preflight",
        );
        assert!(render(&explicit_preparation).is_err());
        let weakened =
            SOURCE_BYTES.replace("cargo test --workspace --doc", "true # doctests removed");
        assert!(render(&weakened).is_err());
        let missing_artifact = SOURCE_BYTES.replace(
            "--artifact schemas/ripr/review-comments.schema.json=target/ripr/review/comments.json",
            "",
        );
        assert!(render(&missing_artifact).is_err());
        let reordered = SOURCE_BYTES
            .replace("name: PR evidence", "name: Schema producer sweep")
            .replace(
                "name: Schema producer sweep\n        id: schema_producer_sweep",
                "name: PR evidence\n        id: schema_producer_sweep",
            );
        assert!(render(&reordered).is_err());
    }
}
