#[test]
fn given_native_capture_inventory_when_imported_then_all_eight_observations_remain_unattested()
-> TestResult {
    let provenance = parse(PROVENANCE)?;
    let runs = provenance["runs"].as_array().ok_or("capture runs")?;
    assert_eq!(runs.len(), 8);
    let expected_ids: BTreeSet<_> = CAPTURE_CASES.iter().map(|case| case.id).collect();
    assert_eq!(expected_ids.len(), 8);
    let actual_ids = runs
        .iter()
        .map(|run| run["id"].as_str().ok_or("capture id"))
        .collect::<Result<BTreeSet<_>, _>>()?;
    assert_eq!(actual_ids, expected_ids);
    let actual_files = fs::read_dir(fixture_dir().join("native-captures"))?
        .map(|entry| entry.map(|entry| entry.file_name().to_string_lossy().into_owned()))
        .collect::<Result<BTreeSet<_>, _>>()?;
    let mut expected_files: BTreeSet<_> = expected_ids
        .iter()
        .map(|id| format!("{id}.native.json"))
        .collect();
    expected_files.extend([
        "README.md".into(),
        "proof.rs.txt".into(),
        "provenance.json".into(),
    ]);
    assert_eq!(actual_files, expected_files);
    assert_eq!(provenance["provenance"], "external_unattested");
    assert_eq!(
        provenance["producer"]["commit"],
        "744b3e84d6eb68fd5456826997568666791bd355"
    );
    assert_eq!(provenance["producer"]["tracked_diff_empty"], true);
    assert_eq!(provenance["source"]["retained_file"], "proof.rs.txt");
    assert_eq!(provenance["source"]["native_filename"], "proof.rs");
    assert_eq!(provenance["unmatched_selector"]["process_exit_code"], 1);
    assert_eq!(
        provenance["unmatched_selector"]["native_export_exists"],
        false
    );
    for case in &CAPTURE_CASES {
        let fixture = Fixture::new(case)?;
        let report = fixture.assert_imported(case)?;
        let native = &report["native"]["document"];
        assert_eq!(native["kani_commit"], provenance["producer"]["commit"]);
        assert_eq!(native["kani_commit_dirty"], false);
        let harness = &native["harnesses"][0];
        if matches!(
            case.id,
            "bounded-success" | "insufficient-bound" | "partial"
        ) {
            assert_eq!(harness["resolved_unwind"], 3);
            // This native flag describes automatic argument generation, not
            // whether the proof used a finite loop-unwind bound.
            assert_eq!(harness["is_bounded"], false);
        }
        if case.id == "vacuous" {
            assert_eq!(
                harness["checks"]["unreachable"],
                json!(["c_vacuous.assertion.1"])
            );
            assert_eq!(
                harness["covers"]["unreachable"],
                json!(["c_vacuous.cover.1"])
            );
            assert_eq!(harness["covers"]["satisfied"], json!([]));
        }
        if matches!(case.id, "insufficient-bound" | "partial") {
            assert_eq!(
                harness["checks"]["failure"],
                json!(["g_insufficient_bound.unwind.0"])
            );
            assert_eq!(
                harness["checks"]["undetermined"]
                    .as_array()
                    .ok_or("undetermined checks")?
                    .len(),
                31
            );
        }
        fixture.close()?;
    }
    Ok(())
}

#[test]
fn given_changed_source_or_export_when_binding_is_unchanged_then_import_refuses() -> TestResult {
    let case = &CAPTURE_CASES[0];
    let source = Fixture::new(case)?;
    let changed = CAPTURED_SOURCE.replace("x + 1", "x + 2");
    assert_ne!(changed, CAPTURED_SOURCE, "source control changes bytes");
    fs::write(source.root.join("proof.rs"), changed)?;
    source.assert_refused(&[], "source digest mismatch")?;
    source.close()?;

    let mut export = Fixture::new(case)?;
    export.native = CAPTURE_CASES[1].native.into();
    assert_ne!(export.native, case.native, "export control changes bytes");
    export.write_inputs()?;
    export.assert_refused(&[], "artifact digest mismatch")?;
    export.close()?;

    let lock = Fixture::new(&CONTRACT_CASES[0])?;
    fs::write(lock.root.join("Cargo.lock"), "version = 3\n")?;
    lock.assert_refused(&[], "source digest mismatch")?;
    lock.close()
}

#[test]
