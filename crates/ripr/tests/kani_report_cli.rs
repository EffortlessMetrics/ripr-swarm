fn digest(bytes: &[u8]) -> String {
    format!("sha256:{:x}", Sha256::digest(bytes))
}

fn parse(text: &str) -> TestResult<Value> {
    Ok(serde_json::from_str(text)?)
}

fn fixture_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("src/app/kani_import/fixtures")
}

struct Fixture {
    root: PathBuf,
    native: String,
    binding: Value,
    cleanup_armed: bool,
}

impl Fixture {
    fn new(case: &Case) -> TestResult<Self> {
        static NEXT: AtomicU64 = AtomicU64::new(0);
        let parent = std::env::temp_dir();
        fs::create_dir_all(&parent)?;
        let root = parent.join(format!(
            "ripr-kani-cli-{}-{}-{}",
            std::process::id(),
            NEXT.fetch_add(1, Ordering::Relaxed),
            case.id
        ));
        // Exclusive creation: an existing path is never adopted or removed.
        fs::create_dir(&root)?;
        let mut fixture = Self {
            root,
            native: case.native.into(),
            binding: Value::Null,
            cleanup_armed: true,
        };
        // Install the cleanup guard before any fallible fixture preparation.
        // Child cwd changes must not reinterpret a relative TMPDIR-derived root.
        fixture.root = fixture.root.canonicalize()?;
        let sources = if case.captured {
            vec![(
                "proof.rs",
                CAPTURED_SOURCE,
                json!(["implementation", "harness"]),
            )]
        } else {
            vec![
                ("Cargo.lock", "version = 4\n", json!(["lockfile"])),
                (
                    "test.rs",
                    CONTRACT_SOURCE,
                    json!(["implementation", "harness"]),
                ),
            ]
        };
        let mut source_files = Vec::new();
        let mut inventory = String::new();
        // Both inventories above are in path order, as the published wire
        // contract requires. No importer or private test helper computes it.
        for (path, contents, roles) in sources {
            fs::write(fixture.root.join(path), contents)?;
            let sha256 = digest(contents.as_bytes());
            inventory.push_str(&format!("{path}\t{sha256}\n"));
            source_files.push(json!({"path": path, "sha256": sha256, "roles": roles}));
        }
        let source_digest = digest(inventory.as_bytes());
        let crate_name = if case.captured { "proof" } else { "test" };
        let mut selected = vec![json!({"crate_name": crate_name, "name": case.name})];
        if case.id == "partial" {
            selected.push(json!({"crate_name": "proof", "name": "b_success"}));
        }
        if case.captured {
            let provenance = parse(PROVENANCE)?;
            let runs = provenance["runs"].as_array().ok_or("capture run array")?;
            let records: Vec<_> = runs.iter().filter(|run| run["id"] == case.id).collect();
            assert_eq!(records.len(), 1, "{} provenance identity", case.id);
            let record = records.first().ok_or("capture record")?;
            assert_eq!(record["native_sha256"], digest(case.native.as_bytes()));
            assert_eq!(record["selected_harnesses"], json!(selected));
            assert_eq!(
                provenance["source"]["sha256"],
                digest(CAPTURED_SOURCE.as_bytes())
            );
            assert_eq!(provenance["source"]["inventory_digest"], source_digest);
            assert_eq!(
                record["process_exit_code"],
                if case.verdict == "SUCCESS" { 0 } else { 1 }
            );
            assert_eq!(record["fresh_export_path"], true);
            assert_eq!(record["source_unchanged"], true);
        }
        // This is a newly authored portable binding, never the original
        // capture binding. Its invocation is descriptive data, not execution.
        fixture.binding = json!({
            "schema_version": "ripr_kani_binding.v1",
            "repository": {
                "repository_id": "authored-kani-cli-fixture",
                "snapshot_id": format!("captured:{source_digest}"),
                "source_view": "captured_source_set",
                "source_digest": source_digest,
            },
            "run_id": format!("authored-cli-replay-{}", case.id),
            "artifact_sha256": digest(case.native.as_bytes()),
            "source_files": source_files,
            "context": {
                "target": "x86_64-unknown-linux-gnu",
                "cargo_features": [],
                "default_features": !case.captured,
                "toolchain": if case.captured {
                    "nightly-2026-10-23-x86_64-unknown-linux-gnu"
                } else {
                    "upstream-contract-fixture"
                },
                "environment_sha256": digest(b"authored offline CLI replay; no verifier execution"),
                "invocation": [
                    "kani",
                    if case.captured { "proof.rs" } else { "test.rs" },
                    "--export-json",
                    "replay.json",
                ],
            },
            "selected_harnesses": selected,
        });
        fixture.write_inputs()?;
        Ok(fixture)
    }

    fn write_inputs(&self) -> TestResult {
        fs::write(self.root.join("native.json"), &self.native)?;
        fs::write(
            self.root.join("binding.json"),
            serde_json::to_vec(&self.binding)?,
        )?;
        Ok(())
    }

    fn run(&self, extra: &[(&str, &Path)]) -> TestResult<Output> {
        let mut command = Command::new(env!("CARGO_BIN_EXE_ripr"));
        command
            .current_dir(&self.root)
            .args(["reports", "kani", "--root"])
            .arg(&self.root)
            .arg("--input")
            .arg(self.root.join("native.json"))
            .arg("--binding")
            .arg(self.root.join("binding.json"));
        for (flag, path) in extra {
            command.arg(flag).arg(path);
        }
        Ok(command.output()?)
    }

    fn report_path(&self, extension: &str) -> PathBuf {
        self.root
            .join(format!("target/ripr/reports/kani.{extension}"))
    }

    fn close(mut self) -> TestResult {
        // Normal completion must report cleanup failure. Drop still attempts
        // cleanup when preparation, an assertion or another operation fails.
        fs::remove_dir_all(&self.root)?;
        self.cleanup_armed = false;
        Ok(())
    }

    fn assert_refused(&self, extra: &[(&str, &Path)], reason: &str) -> TestResult {
        let output = self.run(extra)?;
        let stderr = String::from_utf8_lossy(&output.stderr);
        assert_eq!(output.status.code(), Some(2), "{stderr}");
        assert!(stderr.contains(reason), "expected {reason:?}, got {stderr}");
        assert!(!String::from_utf8_lossy(&output.stdout).contains("Wrote "));
        assert!(!self.report_path("json").exists());
        assert!(!self.report_path("md").exists());
        Ok(())
    }

    fn expected_report(&self, case: &Case) -> TestResult<Value> {
        let partial = case.id == "partial";
        let checked_root = self.root.canonicalize()?;
        Ok(json!({
            "schema_version": "ripr_kani_report.v1",
            "adapter_version": env!("CARGO_PKG_VERSION"),
            "adapter_profile": "kani-export-0.1.0@744b3e84d6eb68fd5456826997568666791bd355",
            "provenance": "external_unattested",
            "source_binding_state": "listed_files_match",
            "checked_root": checked_root.to_str().ok_or("UTF-8 fixture root")?,
            "artifact_sha256": digest(self.native.as_bytes()),
            "binding_sha256": digest(&fs::read(self.root.join("binding.json"))?),
            "binding": self.binding,
            "native": {
                "schema_version": "0.1.0",
                "run_state": if partial { "PARTIAL" } else { "COMPLETE" },
                "target": "x86_64-unknown-linux-gnu",
                "matched_count": if partial { 2 } else { 1 },
                "missing_count": if partial { 1 } else { 0 },
                "harnesses": [{
                    "crate_name": if case.captured { "proof" } else { "test" },
                    "name": case.name,
                    "file": if case.captured { "proof.rs" } else { "test.rs" },
                    "line": case.line,
                    "should_panic": case.should_panic,
                    "outcome": {
                        "kind": "COMPLETED",
                        "verdict": case.verdict,
                        "failure_kind": case.failure_kind,
                    },
                    "checks_total": case.counts[0],
                    "checks_success": case.counts[1],
                    "covers_total": case.counts[2],
                }],
                "document": parse(&self.native)?,
            },
            "limitations": LIMITATIONS,
        }))
    }

    fn assert_imported(&self, case: &Case) -> TestResult<Value> {
        let output = self.run(&[])?;
        assert_eq!(
            output.status.code(),
            Some(0),
            "{}: {}",
            case.id,
            String::from_utf8_lossy(&output.stderr)
        );
        let json = fs::read_to_string(self.report_path("json"))?;
        let actual = parse(&json)?;
        // Complete owned envelope equality rejects added promotion fields as
        // well as missing limitations. Raw external payloads are not masked.
        assert_eq!(actual, self.expected_report(case)?, "{} report", case.id);
        let markdown = fs::read_to_string(self.report_path("md"))?;
        let embedded = markdown
            .lines()
            .filter_map(|line| line.strip_prefix("    "))
            .collect::<Vec<_>>()
            .join("\n");
        assert_eq!(
            embedded,
            json.trim_end(),
            "{} Markdown observation",
            case.id
        );
        assert!(
            markdown
                .contains("Import succeeded. Native verification outcomes are listed separately")
        );
        assert!(markdown.contains("external, unattested"));
        assert!(markdown.lines().any(|line| {
            line.starts_with("| `")
                && line.contains(case.name)
                && line.contains(case.verdict)
                && line.ends_with(&format!(
                    "| {} | {} | {} | {} |",
                    case.should_panic, case.counts[1], case.counts[0], case.counts[2]
                ))
        }));
        Ok(actual)
    }
}

impl Drop for Fixture {
    fn drop(&mut self) {
        if self.cleanup_armed {
            let _ = fs::remove_dir_all(&self.root);
        }
    }
}

