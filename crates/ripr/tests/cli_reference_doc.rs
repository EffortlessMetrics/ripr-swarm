//! `docs/CLI_REFERENCE.md` is generated from the shipped binary and checked.
//!
//! The document is rendered from `ripr --help`, the `ripr help --json`
//! command catalog, and each command's own `ripr help <command>` body, so it
//! cannot drift from what the binary prints. Regenerate after changing a
//! command or its help text:
//!
//! ```text
//! RIPR_BLESS_CLI_REFERENCE=1 cargo test -p ripr --test cli_reference_doc
//! ```

use std::collections::BTreeMap;
use std::process::Command;

const DOC_PATH: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../../docs/CLI_REFERENCE.md");

fn spawn(args: &[&str]) -> Result<std::process::Output, String> {
    Command::new(env!("CARGO_BIN_EXE_ripr"))
        .args(args)
        .output()
        .map_err(|error| format!("failed to run ripr {args:?}: {error}"))
}

fn run(args: &[&str]) -> Result<String, String> {
    let output = spawn(args)?;
    if !output.status.success() {
        return Err(format!("ripr {args:?} failed: {:?}", output.status));
    }
    String::from_utf8(output.stdout).map_err(|error| format!("non-utf8 output: {error}"))
}

/// Extended help (`ripr help <command> --all`) where the command has it; the
/// binary refuses `--all` on commands without an extended reference.
fn extended_help(path: &str) -> Option<String> {
    let mut args = vec!["help"];
    args.extend(path.split(' '));
    args.push("--all");
    let output = spawn(&args).ok()?;
    if !output.status.success() {
        return None;
    }
    String::from_utf8(output.stdout)
        .ok()
        .map(|body| body.trim_end().to_string())
}

fn text<'a>(value: &'a serde_json::Value, key: &str) -> &'a str {
    value[key].as_str().unwrap_or("")
}

fn render() -> Result<String, String> {
    let catalog: serde_json::Value =
        serde_json::from_str(&run(&["help", "--json"])?).map_err(|error| error.to_string())?;
    let commands = catalog["commands"].as_array().ok_or("commands missing")?;

    let mut out = String::new();
    out.push_str("# CLI reference\n\n");
    out.push_str(
        "<!-- Generated by crates/ripr/tests/cli_reference_doc.rs. Do not edit by hand;\n     run `RIPR_BLESS_CLI_REFERENCE=1 cargo test -p ripr --test cli_reference_doc`. -->\n\n",
    );
    out.push_str(
        "Every `ripr` command and option, copied from the binary's own help. For a\nguided start, read the [Quickstart](QUICKSTART.md). For exit codes, see\n[EXIT_CODES.md](EXIT_CODES.md). In a terminal, `ripr help <command>` prints the\nsame text for one command and `ripr help --json` prints the machine-readable\ncatalog.\n\n",
    );

    out.push_str("## Overview\n\n```text\n");
    out.push_str(run(&["--help"])?.trim_end());
    out.push_str("\n```\n\n");

    // Commands that share one help body (a group and its subcommands) are
    // documented once, under the first command that prints it. A family leaf
    // swaps only the body's lead summary line for its own catalog summary,
    // which the Commands table already shows, so bodies are compared without
    // that line; the section prints the first command's full text. Compatibility
    // spellings are visited last so a shared section is titled by the
    // canonical command.
    let mut section_of: BTreeMap<String, String> = BTreeMap::new();
    let mut by_body: BTreeMap<String, Vec<String>> = BTreeMap::new();
    let mut full_body: BTreeMap<String, String> = BTreeMap::new();
    let mut order: Vec<String> = Vec::new();
    let (canonical, compatibility): (Vec<_>, Vec<_>) = commands
        .iter()
        .partition(|command| text(command, "class") != "compatibility");
    for command in canonical.into_iter().chain(compatibility) {
        let path = text(command, "path");
        let mut args = vec!["help"];
        args.extend(path.split(' '));
        let text_out = run(&args)?.trim_end().to_string();
        let body = text_out
            .split_once('\n')
            .map_or(text_out.as_str(), |(_, rest)| rest)
            .to_string();
        if !by_body.contains_key(&body) {
            order.push(body.clone());
            full_body.insert(body.clone(), text_out);
        }
        let paths = by_body.entry(body).or_default();
        paths.push(path.to_string());
        section_of.insert(path.to_string(), paths[0].replace(' ', "-"));
    }

    out.push_str("## Commands\n\n| Command | Summary | Class |\n| --- | --- | --- |\n");
    for command in commands {
        let path = text(command, "path");
        // A command folded into a shared section links to that section.
        let anchor = section_of.get(path).cloned().unwrap_or_default();
        out.push_str(&format!(
            "| [`ripr {path}`](#{anchor}) | {} | {} |\n",
            text(command, "summary"),
            text(command, "class"),
        ));
    }
    out.push('\n');

    out.push_str("## Help text by command\n");
    for key in order {
        let paths = &by_body[&key];
        let body = &full_body[&key];
        out.push_str(&format!("\n### {}\n\n", paths[0].replace(' ', "-")));
        if paths.len() > 1 {
            let shared: Vec<String> = paths.iter().map(|p| format!("`ripr {p}`")).collect();
            out.push_str(&format!("Shared help for {}.\n\n", shared.join(", ")));
        } else {
            out.push_str(&format!("`ripr help {}`\n\n", paths[0]));
        }
        out.push_str("```text\n");
        out.push_str(body);
        out.push_str("\n```\n");
        if let Some(extended) = extended_help(&paths[0]).filter(|extended| extended != body) {
            out.push_str(&format!(
                "\nEvery option: `ripr help {} --all`\n\n```text\n",
                paths[0]
            ));
            out.push_str(&extended);
            out.push_str("\n```\n");
        }
    }
    Ok(out)
}

#[test]
fn cli_reference_matches_the_binary() -> Result<(), String> {
    let expected = render()?;
    if std::env::var_os("RIPR_BLESS_CLI_REFERENCE").is_some() {
        std::fs::write(DOC_PATH, &expected).map_err(|error| error.to_string())?;
        return Ok(());
    }
    let actual = std::fs::read_to_string(DOC_PATH)
        .map_err(|error| format!("docs/CLI_REFERENCE.md unreadable: {error}"))?;
    assert!(
        actual == expected,
        "docs/CLI_REFERENCE.md is stale; run `RIPR_BLESS_CLI_REFERENCE=1 cargo test -p ripr --test cli_reference_doc`"
    );
    Ok(())
}

/// User-facing help must not send readers to repository-internal tracking:
/// issue numbers and spec identifiers mean nothing to someone running the
/// binary.
#[test]
fn help_text_carries_no_issue_or_spec_references() -> Result<(), String> {
    let document = render()?;
    let mut offenders = Vec::new();
    for (index, line) in document.lines().enumerate() {
        let bytes = line.as_bytes();
        let issue_ref = bytes
            .windows(4)
            .any(|window| window[0] == b'#' && window[1..].iter().all(u8::is_ascii_digit));
        if issue_ref || line.contains("RIPR-SPEC-") {
            offenders.push(format!("{}: {line}", index + 1));
        }
    }
    assert!(
        offenders.is_empty(),
        "help text names internal references:\n{}",
        offenders.join("\n")
    );
    Ok(())
}
