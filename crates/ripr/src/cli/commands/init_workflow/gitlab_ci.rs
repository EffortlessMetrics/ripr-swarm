//! The generated `ripr init --ci gitlab` pipeline template (#2019).
//!
//! One advisory merge-request flow: install the pinned ripr release, run
//! `ripr check` and `ripr review-comments` on the MR diff, upload
//! `target/ripr/**` artifacts. No gate modes, SARIF, or comment publishing.

use super::{install_pin_first_line, workflow_install_version};

const GITLAB_CI_TEMPLATE: &str = r#"# RIPR advisory merge-request flow (generated by ripr init --ci gitlab)
# CI guide: https://github.com/EffortlessMetrics/ripr/blob/main/docs/CI.md

variables:
  GIT_DEPTH: "0"

ripr-advisory:
  image: rust:1
  allow_failure: true
  rules:
    - if: $CI_PIPELINE_SOURCE == "merge_request_event"
  before_script:
    - rm -rf target/ripr target/ci
    - mkdir -p target/ripr/pr target/ripr/review
@RIPR_PIN_FIRST_LINE@
    - |
      version="@RIPR_VERSION@"
      base="https://github.com/EffortlessMetrics/ripr/releases/download/v${version}"
      file="ripr-server-v${version}-x86_64-unknown-linux-gnu.tar.gz"
      if curl -fsSLO "$base/$file" && curl -fsSLO "$base/$file.sha256"; then
        expected="$(awk 'NR == 1 { print $1 }' "$file.sha256")"
        actual="$(sha256sum "$file" | awk '{ print $1 }')"
        if [ -z "$expected" ] || [ "$expected" != "$actual" ]; then
          echo "ERROR: $file does not match its published SHA-256 (expected ${expected:-nothing}, got $actual)" >&2
          exit 1
        fi
        tar xzf "$file"
        export PATH="$PWD:$PATH"
      else
        if ! command -v cargo >/dev/null 2>&1; then
          echo "ERROR: cannot install ripr ${version}: download failed and cargo is missing" >&2
          exit 1
        fi
        cargo install ripr --version @RIPR_VERSION@ --locked
      fi
      reported="$(ripr --version)"
      case "$reported" in "ripr @RIPR_VERSION@" | "ripr @RIPR_VERSION@ "*) ;; *)
        echo "ERROR: installed ripr reports \"$reported\", not ripr @RIPR_VERSION@" >&2
        exit 1
      esac
  script:
    - |
      base_ref="origin/${CI_MERGE_REQUEST_TARGET_BRANCH_NAME}"
      mkdir -p target/ripr/pr target/ripr/review
      ripr check --root . --base "$base_ref" --head "$CI_COMMIT_SHA" --format json > target/ripr/pr/check.json
      ripr review-comments --root . --base "$base_ref" --head "$CI_COMMIT_SHA" --check-output target/ripr/pr/check.json --out target/ripr/review/comments.json
  artifacts:
    when: always
    paths:
      - target/ripr/
    expire_in: 14 days
"#;

pub(super) fn generated_gitlab_ci_yaml() -> String {
    generated_gitlab_ci_for_version(env!("CARGO_PKG_VERSION"))
}

pub(super) fn generated_gitlab_ci_for_version(version: &str) -> String {
    let pinned = workflow_install_version(version);
    let github_style = install_pin_first_line(version, &pinned);
    let pin_line = github_style
        .trim_start()
        .strip_prefix('#')
        .map(|rest| format!("#{rest}"))
        .unwrap_or_else(|| format!("# {}", github_style.trim()));
    GITLAB_CI_TEMPLATE
        .replace("@RIPR_VERSION@", &pinned)
        .replace("@RIPR_PIN_FIRST_LINE@", &pin_line)
}

#[cfg(test)]
mod tests {
    use super::{generated_gitlab_ci_for_version, generated_gitlab_ci_yaml};

    #[test]
    fn generated_gitlab_ci_is_advisory_merge_request_only() {
        let yaml = generated_gitlab_ci_yaml();
        assert!(yaml.contains("allow_failure: true"));
        assert!(yaml.contains(r#"$CI_PIPELINE_SOURCE == "merge_request_event""#));
        assert!(yaml.contains("ripr check --root ."));
        assert!(yaml.contains("ripr review-comments --root ."));
        assert!(yaml.contains("target/ripr/"));
        assert!(!yaml.contains("RIPR_GATE_MODE"));
        assert!(!yaml.contains("upload-sarif"));
    }

    #[test]
    fn generated_gitlab_ci_substitutes_every_placeholder() {
        let yaml = generated_gitlab_ci_for_version("9.9.9");
        assert!(
            !yaml.contains("@RIPR_"),
            "unsubstituted placeholder:\n{yaml}"
        );
    }
}
