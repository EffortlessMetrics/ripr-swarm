//! Owner-return pins (#4478): an `assert_eq!` whose operand is a call of
//! the changed owner pins the owner's whole return value, so it observes a
//! changed `return_value` expression without sharing a token with it.
//!
//! Crediting that assertion is only sound when three facts hold, and each
//! gate below fails closed when ripr cannot establish one:
//!
//! 1. The call names the owner. A bare `name(..)` names a module-level
//!    function, never an associated function or a trait method. A method
//!    call `recv.name(..)` names a function with a `self` receiver, and only
//!    when the receiver's type dispatches to the owner: the test binds the
//!    receiver to a type ripr can read, no type declaration in the test's
//!    own module scope shadows that name, that type reaches the owner's
//!    `impl` or trait, and no other definition of `name` in the workspace
//!    could take the call instead.
//! 2. The call's return value came through the changed expression. The
//!    changed expression must be the owner's tail and must evaluate all of
//!    its parts on every input (no closure, `&&`/`||`, branch, or skipping
//!    combinator such as `map_or`). When the owner has other
//!    exits (`?`, `return`), the changed expression must be the owner's only
//!    `Ok(..)` (or `Some(..)`) constructor and the pinned value must be that
//!    constructor too: an `Err(..)` pin observes an early exit that never
//!    evaluates the changed `Ok(..)`.
//! 3. The pinned value is the whole return value: one plain `assert_eq!`
//!    in the test's own body with the call as a complete operand, nothing
//!    chained after it, and an expected value that does not call the owner
//!    again. `assert_ne!`, `debug_assert_eq!` and a `#[should_panic]` test
//!    pin nothing. Its exact parser context must also establish an eager
//!    statement path (or a directly invoked bounded closure), and no visible
//!    workspace macro definition/import may compete with `assert_eq!`.
//!    Deferred, conditional and ambiguous contexts do not supply this pin.
//!
//! This is bounded syntax, not name resolution. The documented residuals:
//! methods generated by derive or attribute macros are invisible, a
//! `macro_rules!` body that defines the method counts only when ripr can
//! read its `fn` text, and an out-of-workspace trait in scope that also
//! names the method is not detected.

