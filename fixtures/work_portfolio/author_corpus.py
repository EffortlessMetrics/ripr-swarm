def deep_reverse_lists(value):
    if isinstance(value, dict):
        return {key: deep_reverse_lists(child) for key, child in value.items()}
    if isinstance(value, list):
        return [deep_reverse_lists(child) for child in reversed(value)]
    return value


def variant_unix_root():
    return canonical(UNIX_ROOT)


def variant_reordered():
    return {name: deep_reverse_lists(copy.deepcopy(body)) for name, body in canonical().items()}


def variant_missing_github():
    state_map = {
        "github_issues": "missing",
        "github_pull_requests": "missing",
        "github_claims": "missing",
    }
    files = canonical()
    files["manifest.json"] = manifest(WIN_ROOT, state_map)
    for name in ("issues.json", "pull_requests.json", "claims.json"):
        del files[name]
    return files


def variant_stale_local():
    files = canonical()
    observed_map = {"local_state": STALE_AT}
    files["manifest.json"] = manifest(WIN_ROOT, {}, observed_map)
    return files


def variant_no_cargo_allow():
    files = canonical()
    files["manifest.json"] = manifest(WIN_ROOT, {"cargo_allow": "unavailable"})
    del files["cargo_allow.json"]
    return files


