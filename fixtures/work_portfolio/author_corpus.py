def sources(state_map, observed_map=None, request_id="req-captured-0001"):
    observed_map = observed_map or {}
    rows = []
    for kind in [
        "github_issues",
        "github_pull_requests",
        "github_claims",
        "local_state",
        "cargo_allow",
        "campaigns",
        "surfaces",
    ]:
        state = state_map.get(kind, "observed")
        row = {"source": kind, "state": state}
        if state in ("observed", "stale"):
            row["observed_at"] = observed_map.get(kind, OBSERVED_AT)
            row["request_id"] = request_id
        rows.append(row)
    return rows


