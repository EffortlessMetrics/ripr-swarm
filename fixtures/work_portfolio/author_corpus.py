def write_json(path, body):
    path.parent.mkdir(parents=True, exist_ok=True)
    text = json.dumps(body, indent=2, sort_keys=False) + "\n"
    path.write_text(text, encoding="utf-8", newline="\n")
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def main():
    provenance = {
        "schema_version": "work_portfolio_provenance.v1",
        "repository": REPOSITORY,
        "captured_at": CAPTURED_AT,
        "capture_method": "authored captured-input corpora for the RIPR-SPEC-0233 work-portfolio compiler; regenerate with fixtures/work_portfolio/author_corpus.py",
        "corpora": [],
    }
    for name, builder in VARIANTS.items():
        files = builder()
        entries = []
        for file_name in sorted(files):
            digest = write_json(HERE / name / file_name, files[file_name])
            entries.append({"path": file_name, "sha256": digest})
        provenance["corpora"].append({"name": name, "files": entries})
    write_json(HERE / "provenance.json", provenance)
    print(f"authored {len(VARIANTS)} corpora under {HERE}")


if __name__ == "__main__":
    main()
